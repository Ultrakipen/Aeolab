def get_guide(category: str, cat_name: str) -> PhotoGuideEntry | None:
    """업종+카테고리명으로 가이드 조회. 없으면 None."""
    cats = PHOTO_GUIDES.get(category)
    if not cats:
        return None
    # 정규화: `-` → `·`
    norm = cat_name.replace("-", "·")
    return cats.get(norm) or cats.get(cat_name)


def get_guides_for_category(category: str) -> Dict[str, PhotoGuideEntry]:
    """업종 전체 가이드 사전 반환 (프론트 모달용)."""
    return PHOTO_GUIDES.get(category, {})
