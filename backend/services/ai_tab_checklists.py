def get_checklist(category: str) -> list[dict]:
    """업종명(DB 값) → 체크리스트 dict 목록 반환.

    알 수 없는 업종은 restaurant 체크리스트로 폴백.
    """
    key = normalize_category(category)
    items = AI_TAB_CHECKLISTS.get(key) or AI_TAB_CHECKLISTS.get("restaurant", [])
    return [item.to_dict() for item in items]


def get_checklist_score(category: str, completed_items: list[str]) -> float:
    """완료한 항목 리스트 기준으로 AI탭 준비도 점수(0~100) 계산.

    Args:
        category: DB 업종 값
        completed_items: 완료한 item 텍스트 목록
    Returns:
        0~100 범위의 준비도 점수
    """
    key = normalize_category(category)
    items = AI_TAB_CHECKLISTS.get(key) or AI_TAB_CHECKLISTS.get("restaurant", [])
    if not items:
        return 0.0
    completed_set = set(completed_items)
    score = sum(item.weight for item in items if item.item in completed_set)
    return round(score * 100, 1)


def get_checklist_summary(category: str, completed_items: list[str]) -> dict:
    """체크리스트 전체 요약 (점수 + 미완료 항목)."""
    key = normalize_category(category)
    items = AI_TAB_CHECKLISTS.get(key) or AI_TAB_CHECKLISTS.get("restaurant", [])
    completed_set = set(completed_items)
    score = get_checklist_score(category, completed_items)
    pending = [item.to_dict() for item in items if item.item not in completed_set]
    return {
        "score": score,
        "total_items": len(items),
        "completed_count": len(completed_set & {item.item for item in items}),
        "pending_items": pending,
        "category_key": key,
    }
