"""AI 업체로 보내는 자유 입력 문장에서 연락처 같은 개인정보를 지우는 공용 함수 (2026-11-02 — gemini_scanner에서 옮김).

적용 대상은 **고객이 남긴 리뷰 본문·사용자가 붙여 넣은 자유 문장**이다(방침 5항: 붙여 넣은 고객 리뷰는 Anthropic으로 전송, 약관 제7조 5항: 타인 개인정보는 입력하지 않는다).
**사업장 자신의 전화번호·주소에는 쓰지 않는다** — 11-01 사용자 결정(사업장 연락처는 개인정보가 아니라 프롬프트에 그대로 유지, 소개글 생성 결과에 쓰인다).
그래서 Claude 호출의 공통 관문(anthropic_retry)에서 일괄 적용하지 말고, 고객 리뷰 본문을 넣는 지점에서만 호출한다.
이름·주소 같은 자유 서술은 판별할 수 없어 건드리지 않는다(입력란 안내 문구로 사용자에게 알린다).
"""
import re

_PII_PATTERNS = (
    re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"),                                    # 이메일
    re.compile(r"\+82[-.\s]?\d{1,2}[-.\s]?\d{3,4}[-.\s]?\d{4}"),                    # 국제 표기 전화번호
    re.compile(r"01[016-9][-.\s]?\d{3,4}[-.\s]?\d{4}"),                             # 휴대폰(010·011 등)
    re.compile(r"0\d{1,2}[)\-.\s]\s?\d{3,4}[-.\s]\d{4}"),                           # 지역번호(구분자 필수 — "2020-2024" 같은 연도 범위는 건드리지 않는다)
    re.compile(r"(?<!\d)\d{3}-\d{2}-\d{5}(?!\d)"),                                  # 사업자등록번호
)


def scrub_personal(text: str) -> str:
    """전화번호·이메일·사업자등록번호를 제거한다(이름·주소 같은 자유 서술은 판별 불가라 건드리지 않는다)."""
    out = text or ""
    for pat in _PII_PATTERNS:
        out = pat.sub("", out)
    return out
